package com.aiden.screentopdf.core

import android.graphics.Bitmap
import java.io.File

/*
 * Shared contract for version 2: "rebuild the document" mode.
 *
 * Flow:
 *   FrameSource (processing)  -> List<CapturedPage>   frames in video order, each showing the screen
 *   PageCleaner (processing)  -> List<CapturedPage>   screen straightened, mild clean-up, colours and photos kept
 *   DocumentReader (ai)       -> RebuiltDocument      Claude reads ONLY the document content and ignores the
 *                                                     reader app, toolbars, taskbar, cursor, desktop and so on
 *   DocumentRenderer (render) -> PDF file             typesets the document as real vector text
 *
 * If there is no API key, no internet, or DocumentReader fails, the UI falls back to the
 * old image PDF (Pipeline.pdfBuilder) and tells the user why.
 *
 * Ownership: core/ is owned by the lead. Do not edit this file. Ask the lead for changes.
 */

/** Text with inline styling. A paragraph is a list of runs. */
data class TextRun(
    val text: String,
    val bold: Boolean = false,
    val italic: Boolean = false,
    val underline: Boolean = false,
    val strike: Boolean = false,
    val superscript: Boolean = false,
    val subscript: Boolean = false,
    /** Colour as "#RRGGBB", or null for the normal text colour. */
    val colour: String? = null,
    /** Link target if the text is a hyperlink, else null. */
    val link: String? = null,
)

enum class Align { LEFT, CENTRE, RIGHT, JUSTIFY }

sealed interface DocBlock {
    /** Level 1 is the document title or biggest heading, 4 is the smallest. */
    data class Heading(val level: Int, val runs: List<TextRun>, val align: Align = Align.LEFT) : DocBlock

    data class Paragraph(
        val runs: List<TextRun>,
        val align: Align = Align.LEFT,
        /** Size relative to the body text: 1.0 is normal, 0.8 is small print, 1.2 is larger. */
        val sizeScale: Float = 1.0f,
        /** Left indent in multiples of one list level (0 = none). Used for block quotes and indented text. */
        val indentLevel: Int = 0,
    ) : DocBlock

    /**
     * One item of a bulleted or numbered list.
     * [level] starts at 0. [marker] is the exact marker shown in the original, such as "•", "–", "1.", "a)", "iv.".
     */
    data class ListItem(
        val runs: List<TextRun>,
        val ordered: Boolean,
        val level: Int,
        val marker: String,
    ) : DocBlock

    data class TableCell(
        val runs: List<TextRun>,
        val align: Align = Align.LEFT,
        val colSpan: Int = 1,
        /** Background colour "#RRGGBB" or null. */
        val fill: String? = null,
    )

    data class TableRow(val cells: List<TableCell>, val header: Boolean = false)

    data class Table(
        val rows: List<TableRow>,
        /** Relative column widths that add up to about 1.0, or empty to share the width equally. */
        val columnWidths: List<Float> = emptyList(),
        /** True when the original table draws grid lines between all cells. */
        val gridLines: Boolean = true,
    ) : DocBlock

    /**
     * A picture, chart, logo, signature or diagram copied from a frame.
     * [frameIndex] indexes the cleaned frames list given to DocumentReader.
     * The box is in fractions (0.0 to 1.0) of that frame's width and height.
     * [bitmap] is filled in by DocumentReader (cropped from the frame) so the renderer never needs the frames.
     */
    data class Image(
        val frameIndex: Int,
        val left: Float,
        val top: Float,
        val right: Float,
        val bottom: Float,
        /** Width on the page as a fraction of the text width (0.1 to 1.0). */
        val widthFraction: Float = 1.0f,
        val align: Align = Align.CENTRE,
        val caption: List<TextRun> = emptyList(),
        val bitmap: Bitmap? = null,
    ) : DocBlock

    /** A horizontal line across the page. */
    data object Rule : DocBlock

    /** The original document starts a new page here. */
    data object PageBreak : DocBlock
}

enum class PaperSize { A4, LETTER, SLIDE_16_9 }

data class PageSetup(
    val paper: PaperSize = PaperSize.A4,
    val landscape: Boolean = false,
    /** "serif" (Times-like), "sans" (Arial/Calibri-like) or "mono". */
    val fontFamily: String = "sans",
    /** Body text size in points, usually 10 to 12. */
    val baseFontSizePt: Float = 11f,
    /** Page margin in points on all sides. 72 points = 1 inch. */
    val marginPt: Float = 60f,
    /** Line spacing multiplier for body text, usually 1.0 to 1.5. */
    val lineSpacing: Float = 1.15f,
)

data class RebuiltDocument(
    val title: String,
    val setup: PageSetup,
    val blocks: List<DocBlock>,
    /** Short notes from the reader, such as "page 3 was blurred, 2 words guessed". Shown to the user. */
    val warnings: List<String> = emptyList(),
)

/** Reads frames with Claude and returns the rebuilt document. Owned by the ai package. */
interface DocumentReader {
    /** True when an API key is saved and the reader can be used. */
    fun isReady(): Boolean

    suspend fun read(frames: List<CapturedPage>, onProgress: ProgressListener): RebuiltDocument
}

/** Typesets a RebuiltDocument into a PDF with real, selectable text. Owned by the render package. */
interface DocumentRenderer {
    suspend fun render(doc: RebuiltDocument, outFile: File, onProgress: ProgressListener): File
}
